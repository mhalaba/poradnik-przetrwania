# polskie znaki: litera bazowa + znak diakrytyczny dorysowany osobno
DIAKRYTY = {
    'Ą':('A','ogonek'), 'Ć':('C','kreska'), 'Ę':('E','ogonek'), 'Ł':('L','przekreslenie'),
    'Ń':('N','kreska'), 'Ó':('O','kreska'), 'Ś':('S','kreska'), 'Ź':('Z','kreska'), 'Ż':('Z','kropka'),
}

def rysuj_znak(pisz, ch, x, y, s, kolor):
    """pisz(px,py,kolor) stawia jeden piksel logiczny; s = skala (1 = 5x7)."""
    baza, diak = DIAKRYTY.get(ch, (ch, None))
    wzor = G.get(baza) or G.get(baza.upper()) or G[' ']
    for ry, rzad in enumerate(wzor):
        for rx, c in enumerate(rzad):
            if c == '#':
                for a in range(s):
                    for b in range(s):
                        pisz(x+rx*s+a, y+ry*s+b, kolor)
    if diak == 'kreska':          # akut nad litera
        for rx, ry in ((2,-2),(3,-3)):
            for a in range(s):
                for b in range(s):
                    pisz(x+rx*s+a, y+ry*s+b, kolor)
    elif diak == 'kropka':        # kropka nad Z
        for a in range(s):
            for b in range(s):
                pisz(x+2*s+a, y-2*s+b, kolor)
    elif diak == 'ogonek':        # ogonek pod litera
        for rx, ry in ((3,7),(3,8),(2,8)):
            for a in range(s):
                for b in range(s):
                    pisz(x+rx*s+a, y+ry*s+b, kolor)
    elif diak == 'przekreslenie': # ukosnik przez L
        for rx, ry in ((1,3),(2,2)):
            for a in range(s):
                for b in range(s):
                    pisz(x+rx*s+a, y+ry*s+b, kolor)

def szerokosc(txt, s, odstep=1):
    return len(txt)*(5*s+odstep*s) - odstep*s

def rysuj_tekst(pisz, txt, x, y, s, kolor, odstep=1):
    kx = x
    for ch in txt:
        rysuj_znak(pisz, ch, kx, y, s, kolor)
        kx += (5+odstep)*s
    return kx
